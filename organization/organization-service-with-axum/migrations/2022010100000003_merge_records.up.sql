-- The `merge_records` table: one row per record merge, capturing the
-- survivor, the merged-away duplicate, an optional reason/actor, and a
-- snapshot of the duplicate's transferred payload.
CREATE TABLE merge_records (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    -- The surviving (main) organization pid.
    main_pid uuid NOT NULL,
    -- The merged-away (duplicate) pid, now soft-deleted.
    duplicate_pid uuid NOT NULL,
    -- Optional operator-supplied reason.
    reason character varying,
    -- Optional actor (user id / system).
    actor character varying,
    -- Snapshot of the duplicate's payload at merge time.
    transferred jsonb,
    CONSTRAINT merge_records_pkey PRIMARY KEY (id)
);
