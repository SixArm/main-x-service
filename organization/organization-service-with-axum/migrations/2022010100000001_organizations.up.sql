-- The `organizations` table: the service's primary store. The full
-- `organization_matcher::Organization` payload lives in the `data` JSONB
-- column; `pid` and `name` are denormalised for lookup and search.
CREATE TABLE organizations (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    pid uuid NOT NULL,
    name character varying NOT NULL,
    -- Full `organization_matcher::Organization` payload as JSON.
    data jsonb NOT NULL,
    active boolean NOT NULL DEFAULT true,
    deleted_at timestamp with time zone,
    CONSTRAINT organizations_pkey PRIMARY KEY (id),
    CONSTRAINT organizations_pid_key UNIQUE (pid)
);
