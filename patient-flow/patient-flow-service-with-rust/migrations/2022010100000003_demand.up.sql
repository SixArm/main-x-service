-- The demand-side tables: `bed_requests` (the queue the allocator
-- serves), `red_green_days` (the per-stay-per-day journey journal), and
-- `infection_flags` (per-stay IPC precautions).
--
-- Written from a `pg_dump --schema-only` of the database the SeaORM
-- schema-builder migration produced.

CREATE TABLE bed_requests (
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pid uuid NOT NULL UNIQUE,
    -- The patient needing a bed: `person:<pid>` URN.
    person_ref varchar NOT NULL,
    -- ed | elective | ward_transfer | external | virtual_step_up.
    origin varchar NOT NULL,
    target_ward_pid uuid,
    specialty varchar,
    -- emergency | urgent | routine.
    priority varchar NOT NULL,
    -- Requirement flags (JSON): isolation, side_room, oxygen, bariatric,
    -- sex — see `flow::allocation::Requirements`.
    requirements jsonb NOT NULL,
    -- open | allocated | fulfilled | cancelled.
    status varchar NOT NULL,
    allocated_bed_pid uuid,
    requested_at timestamptz NOT NULL,
    resolved_at timestamptz,
    deleted_at timestamptz
);

CREATE TABLE red_green_days (
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stay_pid uuid NOT NULL,
    day date NOT NULL,
    -- red | green — days start red (spec `patient-journey.md`).
    classification varchar NOT NULL,
    -- Coded delay reasons, at most 2 (JSON array of tokens).
    delay_reasons jsonb NOT NULL,
    note varchar
);

CREATE TABLE infection_flags (
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pid uuid NOT NULL UNIQUE,
    stay_pid uuid NOT NULL,
    -- contact | droplet | airborne | protective.
    precaution varchar NOT NULL,
    -- e.g. covid-19, c-diff, mrsa, norovirus.
    organism varchar,
    -- suspected | confirmed | cleared.
    status varchar NOT NULL,
    -- Allocation-rule input: only side rooms / isolation beds.
    requires_side_room boolean NOT NULL DEFAULT false,
    flagged_at timestamptz NOT NULL,
    cleared_at timestamptz
);

CREATE INDEX IF NOT EXISTS bed_requests_status ON bed_requests (status)
    WHERE deleted_at IS NULL;
-- One journal row per stay per day (same-day edits update it).
CREATE UNIQUE INDEX IF NOT EXISTS red_green_stay_day
    ON red_green_days (stay_pid, day);
CREATE INDEX IF NOT EXISTS infection_flags_stay ON infection_flags (stay_pid);
