-- The `audit_logs` table: the who/what/when trail. Stay data is
-- personal data, so every mutation and every sensitive read (patient
-- locate, stay detail) writes one row here recording the entity kind,
-- the action, the (optional) actor, and a snapshot.
--
-- Written from a `pg_dump --schema-only` of the database the SeaORM
-- schema-builder migration produced.

CREATE TABLE audit_logs (
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Which record kind the entry concerns: site | ward | bay | bed |
    -- stay | bed_request | infection_flag | red_green.
    entity varchar NOT NULL,
    -- The record pid the entry concerns.
    entity_pid uuid NOT NULL,
    -- created / updated / deleted / state actions (bed_state_changed,
    -- stay_admitted, ...) / sensitive reads (locate_read, stay_read).
    action varchar NOT NULL,
    -- Optional actor (verified caller `sub`); null until a bearer token
    -- is presented.
    actor varchar,
    -- Snapshot / detail of the action (old + new state, the override
    -- reason, ...).
    snapshot jsonb
);

-- The handover query: audit for one ward since a timestamp rides the
-- snapshot's ward_pid; the common per-record query is indexed.
CREATE INDEX IF NOT EXISTS audit_logs_entity ON audit_logs (entity_pid);
