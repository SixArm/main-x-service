// Lightweight, dependency-free i18n for the Thing front-end SPA. A
// per-locale strings map plus a reactive `$state` current-locale (Svelte 5
// runes), exposed via a `t(key)` accessor. Deliberately no i18n library:
// the surface is small and the front-end family is kept dependency-light.
//
// Supported locales: English (`en`, source of truth) + Welsh (`cy`) for the
// public-sector Welsh-language duty + Spanish (`es`), French (`fr`), German
// (`de`), Arabic (`ar`, RTL), Russian (`ru`), Hindi (`hi`), Mandarin Chinese
// (`zh`), Bengali (`bn`), Portuguese (`pt`), Indonesian (`id`), Urdu (`ur`,
// RTL). Unknown key/locale falls back to `en`. The chosen locale persists
// to localStorage under `mxi.thing.locale`.

import { browser } from "$app/environment";

/**
 * Locales for which the UI is translated. To add one, extend this tuple
 * AND add a matching entry to {@link LOCALE_LABELS} and `STRINGS`.
 */
