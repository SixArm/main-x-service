// Lightweight, dependency-free i18n for the Place front-end. A per-locale
// strings map plus a reactive `$state` current-locale (Svelte 5 runes),
// exposed via a `t(key)` accessor. Deliberately no i18n library: the
// surface is tiny and we keep the front-end dependency-light (drift is
// accepted family-wide; this mirrors the auth front-end's i18n store).
//
// Supported locales (family-wide set, sorted by code): Arabic (`ar-001`,
// RTL), Welsh (`cy-001`, for the public-sector Welsh-language duty),
// German (`de-de`), English (`en-001`, the source of truth), Spanish (`es-001`), French
// (`fr-001`), Hindi (`hi-001`), and Simplified Chinese for China
// (`zh-cn`). `-001` is the UN M.49 code for "world": a language with no
// regional variant. An unknown key/locale falls back to `en-001`. The
// chosen locale persists to localStorage. The chrome's `PickerBar`
// bundles a locale picker alongside theme/text-size/share; `i18n.set()`
// is its `onChange` handler.

import { browser } from "$app/environment";

/**
 * Locales for which the UI is translated, sorted alphabetically by code
 * (the LocalePicker shows them in this order). To add one, extend this
 * tuple AND add a matching entry to {@link LOCALE_LABELS} and `STRINGS`.
 */
export const LOCALES = [
  "ar-001",
  "cy-001",
  "de-de",
  "en-001",
  "es-001",
  "fr-001",
  "hi-001",
  "zh-cn",
] as const;
/** A supported locale code (one of {@link LOCALES}). */
export type Locale = (typeof LOCALES)[number];

/** Fallback locale for an unknown key, locale, or missing translation. */
export const DEFAULT_LOCALE: Locale = "en-001";

/**
 * Right-to-left locales. The layout mirrors this onto `<html dir>` so the
 * whole UI flips for these scripts. Exposed for {@link isRtl}.
 */
export const RTL_LOCALES: readonly Locale[] = ["ar-001"];

/**
 * Whether the given locale renders right-to-left (Arabic).
 *
 * @param locale - A locale code (need not be normalised).
 * @returns `true` for an RTL locale, `false` otherwise.
 */
export function isRtl(locale: string): boolean {
  return (RTL_LOCALES as readonly string[]).includes(locale);
}

