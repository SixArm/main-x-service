-- The `cases` table: the registry of governmental case records. The full
-- `case_matcher::Case` payload is stored as JSONB in `data`; `pid` and
-- `title` are denormalised for lookup and listing.
CREATE TABLE cases (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- Internal auto-increment primary key.
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    -- Public, externally exposed UUID; unique.
    pid uuid NOT NULL,
    -- Denormalised title, for lookup / listing / ILIKE search.
    title character varying NOT NULL,
    -- Full `case_matcher::Case` payload as JSON.
    data jsonb NOT NULL,
    -- Active flag; cleared on soft-delete.
    active boolean NOT NULL DEFAULT true,
    -- Soft-delete timestamp; null while active.
    deleted_at timestamp with time zone,
    CONSTRAINT cases_pkey PRIMARY KEY (id),
    CONSTRAINT cases_pid_key UNIQUE (pid)
);
