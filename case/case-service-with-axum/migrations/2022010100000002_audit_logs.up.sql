-- The `audit_logs` table: the HIPAA-style who/what/when trail. Case data
-- is personal data, so every CRUD/merge action writes one row here
-- recording the action, the (optional) actor, and a snapshot of the
-- record at that time.
CREATE TABLE audit_logs (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    -- The case pid the entry concerns.
    entity_pid uuid NOT NULL,
    -- created / updated / deleted / merged / merged_into.
    action character varying NOT NULL,
    -- Optional actor (verified caller `sub` / system); null until a
    -- bearer token is presented.
    actor character varying,
    -- Snapshot of the record at the time of the action.
    snapshot jsonb,
    CONSTRAINT audit_logs_pkey PRIMARY KEY (id)
);
