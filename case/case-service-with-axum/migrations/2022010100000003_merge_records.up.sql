-- The `merge_records` table: the record-merge history. One row per
-- merge: which duplicate folded into which survivor, by whom, why, and a
-- snapshot of the transferred payload.
CREATE TABLE merge_records (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    -- The surviving (main) case pid.
    main_pid uuid NOT NULL,
    -- The merged-away (duplicate) case pid, now soft-deleted.
    duplicate_pid uuid NOT NULL,
    -- Optional operator-supplied reason.
    reason character varying,
    -- Optional actor (verified caller `sub` / system).
    actor character varying,
    -- Snapshot of the duplicate's payload at merge time.
    transferred jsonb,
    CONSTRAINT merge_records_pkey PRIMARY KEY (id)
);
