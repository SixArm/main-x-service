// Lightweight, dependency-free i18n for the Person SPA. A per-locale
// strings map plus a reactive `$state` current-locale (Svelte 5 runes),
// exposed via a `t(key)` accessor. Deliberately no i18n library: the
// surface is small and we keep the front-end dependency-light (drift
// between front-ends is accepted family-wide).
//
// Supported locales: English (`en`, the source of truth) plus Welsh
// (`cy`, for the public-sector Welsh-language duty), Spanish (`es`),
// French (`fr`), German (`de`), Arabic (`ar`, RTL), Russian (`ru`),
// Hindi (`hi`), Mandarin Chinese (`zh`), Bengali (`bn`), Portuguese
// (`pt`), Indonesian (`id`), and Urdu (`ur`, RTL). An unknown key/locale
// falls back to `en`. The chosen locale persists to localStorage.

import { browser } from "$app/environment";

/**
 * Locales for which the UI is translated. To add one, extend this tuple
 * AND add a matching entry to {@link LOCALE_LABELS} and `STRINGS`.
 */
export const LOCALES = [
  "en",
  "cy",
  "es",
  "fr",
  "de",
  "ar",
  "ru",
  "hi",
  "zh",
  "bn",
  "pt",
  "id",
  "ur",
] as const;
/** A supported locale code (one of {@link LOCALES}). */
export type Locale = (typeof LOCALES)[number];

/** Fallback locale for an unknown key, locale, or missing translation. */
export const DEFAULT_LOCALE: Locale = "en";

/**
 * Right-to-left locales. The document `dir` is set to `rtl` for these and
 * `ltr` for everything else (see {@link isRtl}).
 */
export const RTL_LOCALES = ["ar", "ur"] as const;

/**
 * Whether `locale` is written right-to-left (Arabic, Urdu).
 *
 * @param locale - A supported locale code.
 * @returns `true` for RTL locales, `false` otherwise.
 */
export function isRtl(locale: Locale): boolean {
  return (RTL_LOCALES as readonly string[]).includes(locale);
}

