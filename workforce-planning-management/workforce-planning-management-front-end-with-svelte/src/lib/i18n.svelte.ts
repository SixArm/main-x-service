// Lightweight, dependency-free i18n for the WPM SPA (family pattern,
// copy-adapted from the project-portfolio-management front-end): a
// per-locale strings map plus a reactive `$state` current-locale
// (Svelte 5 runes), exposed via a `t(key)` accessor. `en` is the
// source of truth; every locale must cover the same key set (the
// parity test pins this). The chosen locale persists to localStorage
// and drives the UI strings and `<html dir>` (RTL for `ar` / `ur`).

import { browser } from "$app/environment";

/** Locales the UI is translated into. */
export const LOCALES = [
  "en", "cy", "es", "fr", "de", "ar", "ru", "hi", "zh", "bn", "pt", "id", "ur",
] as const;

/** A supported locale code (one of {@link LOCALES}). */
export type Locale = (typeof LOCALES)[number];

/** Fallback locale for an unknown key, locale, or missing translation. */
export const DEFAULT_LOCALE: Locale = "en";

/** Human-readable name for the locale switcher, written in that locale. */
export const LOCALE_LABELS: Record<Locale, string> = {
  en: "English", cy: "Cymraeg", es: "Español", fr: "Français", de: "Deutsch",
  ar: "العربية", ru: "Русский", hi: "हिन्दी", zh: "中文", bn: "বাংলা",
  pt: "Português", id: "Bahasa Indonesia", ur: "اردو",
};

/** Right-to-left locales; the layout mirrors `<html dir>`. */
export const RTL_LOCALES = ["ar", "ur"] as const satisfies readonly Locale[];

/** Whether `locale` is written right-to-left. */
export function isRtl(locale: string): boolean {
  const primary = normaliseLocale(locale);
  return primary !== null && (RTL_LOCALES as readonly string[]).includes(primary);
}

