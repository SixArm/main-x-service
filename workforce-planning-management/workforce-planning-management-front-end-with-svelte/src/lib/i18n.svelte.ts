// Lightweight, dependency-free i18n for the WPM SPA (family pattern,
// copy-adapted from the project-portfolio-management front-end): a
// per-locale strings map plus a reactive `$state` current-locale
// (Svelte 5 runes), exposed via a `t(key)` accessor.
//
// Supported locales (family-wide set, sorted by code): Arabic (`ar-001`,
// RTL), Welsh (`cy-001`), English (`en-001`, the source of truth),
// Spanish (`es-001`), French (`fr-001`), Hindi (`hi-001`), and Simplified
// Chinese for China (`zh-cn`). `-001` is the UN M.49 code for "world": a
// language with no regional variant. Every locale must cover the same key
// set (the parity test pins this). An unknown key/locale falls back to
// `en-001`. The chosen locale persists to localStorage and drives the UI
// strings and `<html dir>` (RTL for `ar-001`).

import { browser } from "$app/environment";

/**
 * Locales for which the UI is translated, sorted alphabetically by code
 * (the LocalePicker shows them in this order). To add one, extend this
 * tuple AND add a matching entry to {@link LOCALE_LABELS} and `STRINGS`.
 */
export const LOCALES = [
  "ar-001",
  "cy-001",
  "en-001",
  "es-001",
  "fr-001",
  "hi-001",
  "zh-cn",
] as const;

/** A supported locale code (one of {@link LOCALES}). */
export type Locale = (typeof LOCALES)[number];

/** Fallback locale for an unknown key, locale, or missing translation. */
export const DEFAULT_LOCALE: Locale = "en-001";

/**
 * Human-readable name for the locale switcher, written in that locale.
 * A `-001` (world) locale is labelled by its language alone; a regional
 * locale reads "<language> - <region>" (never "<language> (<region>)").
 */
export const LOCALE_LABELS: Record<Locale, string> = {
  "ar-001": "العربية",
  "cy-001": "Cymraeg",
  "en-001": "English",
  "es-001": "Español",
  "fr-001": "Français",
  "hi-001": "हिन्दी",
  "zh-cn": "中文 - 中国",
};

/** Right-to-left locales; the layout mirrors `<html dir>`. */
export const RTL_LOCALES = ["ar-001"] as const satisfies readonly Locale[];

/** Whether `locale` is written right-to-left. */
export function isRtl(locale: string): boolean {
  const resolved = normaliseLocale(locale);
  return (
    resolved !== null && (RTL_LOCALES as readonly string[]).includes(resolved)
  );
}

