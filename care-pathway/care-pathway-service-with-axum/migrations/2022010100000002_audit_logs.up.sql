-- The `audit_logs` table: the CRUD trail. One row per create / update /
-- delete / merge, recording the action, the (optional) actor, and a
-- snapshot of the record at that time.
CREATE TABLE audit_logs (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    -- The care-pathway pid the entry concerns.
    entity_pid uuid NOT NULL,
    -- created / updated / deleted.
    action character varying NOT NULL,
    -- Optional actor (user id / system).
    actor character varying,
    -- Snapshot of the record at the time of the action.
    snapshot jsonb,
    CONSTRAINT audit_logs_pkey PRIMARY KEY (id)
);
