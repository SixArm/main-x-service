-- The `care_pathways` table: the entity store. The full
-- `care_pathway_matcher::CarePathway` payload lives in `data` (JSONB);
-- `pid` and `name` are denormalised for lookup and listing, and
-- `active` / `deleted_at` drive soft-delete.
CREATE TABLE care_pathways (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- Internal auto-increment primary key.
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    -- Public, unique, externally exposed UUID.
    pid uuid NOT NULL,
    -- Denormalised name, for lookup/listing/ILIKE search.
    name character varying NOT NULL,
    -- Full `care_pathway_matcher::CarePathway` payload as JSON.
    data jsonb NOT NULL,
    -- Active flag; cleared on soft-delete.
    active boolean NOT NULL DEFAULT true,
    -- Soft-delete timestamp; null while active.
    deleted_at timestamp with time zone,
    CONSTRAINT care_pathways_pkey PRIMARY KEY (id),
    CONSTRAINT care_pathways_pid_key UNIQUE (pid)
);
