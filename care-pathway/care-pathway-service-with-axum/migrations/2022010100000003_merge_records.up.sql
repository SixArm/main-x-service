-- The `merge_records` table: the merge history. One row per confirmed
-- merge of a duplicate pathway into a surviving one.
CREATE TABLE merge_records (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    -- The surviving (main) pathway pid.
    main_pid uuid NOT NULL,
    -- The merged-away (duplicate) pathway pid, now soft-deleted.
    duplicate_pid uuid NOT NULL,
    -- Optional operator-supplied reason.
    reason character varying,
    -- Optional actor (user id / system).
    actor character varying,
    -- Snapshot of the duplicate's payload at merge time.
    transferred jsonb,
    CONSTRAINT merge_records_pkey PRIMARY KEY (id)
);
