-- The `auth_events` table: the durable authentication audit trail, one
-- row per signup / magic-link request / redemption / signout / me.
-- Columns capture *what happened*, the *subject* (email / pid) when known,
-- and an *outcome* `detail`; never a token or secret.
CREATE TABLE auth_events (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    -- What happened: signup / magic_link_requested / magic_link_redeemed /
    -- signout / me.
    event character varying NOT NULL,
    -- Normalised email when applicable; null otherwise.
    email character varying,
    -- Subject user pid when known; null otherwise.
    user_pid uuid,
    -- Outcome detail, e.g. rate_limited / unknown_email / expired_token.
    -- Never tokens or secrets.
    detail character varying,
    CONSTRAINT auth_events_pkey PRIMARY KEY (id)
);
