-- The `auth_rate_limits` table: the durable, multi-instance backing store
-- for the magic-link issuance rate limiter (spec §7).
--
-- One row is recorded per *allowed* issuance request, keyed by the
-- normalised email (`email_key`) with the wall-clock `requested_at`. The
-- limiter prunes rows older than the window, counts the rest, and inserts
-- a new row only when the count is under the cap — all under a per-key
-- advisory lock so concurrent checks for the same email are exact.
--
-- `created_at`/`updated_at` are the family's conventional columns; the
-- limiter ignores them and uses `requested_at`, which it sets explicitly
-- so tests can inject a synthetic "now".
CREATE TABLE auth_rate_limits (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    email_key character varying NOT NULL,
    requested_at timestamp with time zone NOT NULL,
    CONSTRAINT auth_rate_limits_pkey PRIMARY KEY (id)
);

-- The access pattern of every limiter check: prune + count + min, all
-- scoped to one key.
CREATE INDEX idx_auth_rate_limits_key_requested_at
    ON auth_rate_limits (email_key, requested_at);
