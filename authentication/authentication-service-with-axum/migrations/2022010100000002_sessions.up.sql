-- The `sessions` table: one row per server-side cookie session, keyed by
-- `jid` (the session's opaque id, UNIQUE, stamped into the short-lived
-- PASETO access token's `sid` claim). This is what makes a session
-- *locally* revocable: signout stamps `revoked_at`, and `/me` rejects a
-- revoked session even though a cached token's PASETO signature still
-- verifies. `expires_at` lets stale rows be reaped.
CREATE TABLE sessions (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    jid character varying NOT NULL,
    user_pid uuid NOT NULL,
    expires_at timestamp with time zone NOT NULL,
    revoked_at timestamp with time zone,
    user_agent character varying,
    CONSTRAINT sessions_pkey PRIMARY KEY (id),
    CONSTRAINT sessions_jid_key UNIQUE (jid)
);
