-- The `users` table backing passwordless magic-link accounts.
--
-- `email` and `api_key` are UNIQUE. The password/reset/verification
-- columns are Loco scaffolding; the passwordless flow relies on the
-- `magic_link_token` + `magic_link_expiration` pair (short-lived,
-- single-use). The GDPR `deleted_at` column is added later by
-- 2022010100000004_users_deleted_at.
CREATE TABLE users (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    pid uuid NOT NULL,
    email character varying NOT NULL,
    password character varying NOT NULL,
    api_key character varying NOT NULL,
    name character varying NOT NULL,
    reset_token character varying,
    reset_sent_at timestamp with time zone,
    email_verification_token character varying,
    email_verification_sent_at timestamp with time zone,
    email_verified_at timestamp with time zone,
    magic_link_token character varying,
    magic_link_expiration timestamp with time zone,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT users_email_key UNIQUE (email),
    CONSTRAINT users_api_key_key UNIQUE (api_key)
);
